//! `cargo xtask generate-python-pin-types`: writes `tatolab.stream`'s
//! `_contract_pin_types.py` from the committed control contract file, so it runs on any OS. The
//! module names the built-in pin types, the pin declaration's wire form and the types it
//! reaches, in standard `typing` only. `--check` is the CI gate that fails when the checked-in
//! module differs from a regeneration.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result, bail, ensure};
use serde_json::{Map, Value};
use streamlib_control_contract::CONTROL_CONTRACT_FILE_WORKSPACE_PATH;

use crate::contract_component_references::{
    component_name_of_a_reference, component_names_reached_from, component_schemas_of,
    property_names_of, tags_of_a_tagged_union, the_union_a_schema_is,
};
use crate::contract_pin_types::{
    BUILT_IN_PIN_TYPE_NAME_COMPONENT_NAME, BuiltInPinTypeRow, PIN_ANNOTATIONS_COMPONENT_NAME,
    PIN_TYPE_COMPONENT_NAME, PIN_TYPE_STABILITIES, built_in_pin_type_rows,
};
use crate::generate_built_in_node_classes::{
    push_unique, python_prose, python_string_literal, render_docstring, union_of,
};

pub const GENERATED_PYTHON_PIN_TYPES_PATH: &str =
    "sdk/tatolab-stream/tatolab/stream/_contract_pin_types.py";

/// The components the module renders, with every component they reach.
const PYTHON_PIN_TYPE_ROOT_COMPONENT_NAMES: &[&str] = &[
    BUILT_IN_PIN_TYPE_NAME_COMPONENT_NAME,
    PIN_TYPE_COMPONENT_NAME,
    "PinFlow",
    PIN_ANNOTATIONS_COMPONENT_NAME,
    PIN_DECLARATION_COMPONENT_NAME,
];

const PIN_DECLARATION_COMPONENT_NAME: &str = "PinDeclaration";

/// The column a line of the module wraps before.
const PYTHON_LINE_WIDTH: usize = 88;

/// What the module calls `PinDeclaration`: the dict a node declaration builds is its wire form.
const PIN_DECLARATION_PYTHON_NAME: &str = "PinDeclarationOnTheWire";

/// The component rendered as the `Literal` of its tags only, under the key its alternatives
/// are tagged on.
const NODE_INPUT_MODE_COMPONENT_NAME: &str = "NodeInputMode";
const NODE_INPUT_MODE_TAG_KEY: &str = "mode";

const GENERATED_MODULE_HEADER: &str = r#"# Copyright (c) 2025 Tatolab LLC
# SPDX-License-Identifier: GPL-3.0-only

# Generated by `cargo xtask generate-python-pin-types` from the control
# contract file. Do not edit: CI fails when this file differs from a
# regeneration.

"""Built-in pin types and a pin declaration's wire form, from the control contract."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal, NotRequired, TypedDict
"#;

/// Regenerate the module, or with `check_only` fail when the checked-in one differs from a
/// regeneration.
pub fn run(workspace_root: &Path, check_only: bool) -> Result<()> {
    let contract_file_path = workspace_root.join(CONTROL_CONTRACT_FILE_WORKSPACE_PATH);
    let contract: Value = serde_json::from_str(
        &std::fs::read_to_string(&contract_file_path)
            .with_context(|| format!("reading {}", contract_file_path.display()))?,
    )
    .with_context(|| format!("parsing {}", contract_file_path.display()))?;
    let rendered_module = render_python_pin_types_module(&contract)?;
    let generated_module_path = workspace_root.join(GENERATED_PYTHON_PIN_TYPES_PATH);
    if check_only {
        let checked_in_module = std::fs::read_to_string(&generated_module_path).unwrap_or_default();
        if checked_in_module != rendered_module {
            bail!(
                "{GENERATED_PYTHON_PIN_TYPES_PATH} differs from what \
                 {CONTROL_CONTRACT_FILE_WORKSPACE_PATH} generates: run `cargo xtask \
                 generate-python-pin-types` and commit the result."
            );
        }
        tracing::info!(
            "{GENERATED_PYTHON_PIN_TYPES_PATH} matches {CONTROL_CONTRACT_FILE_WORKSPACE_PATH}"
        );
        return Ok(());
    }
    std::fs::write(&generated_module_path, rendered_module)
        .with_context(|| format!("writing {}", generated_module_path.display()))?;
    tracing::info!(
        "wrote {GENERATED_PYTHON_PIN_TYPES_PATH} from {CONTROL_CONTRACT_FILE_WORKSPACE_PATH}"
    );
    Ok(())
}

/// The module `contract` generates.
pub fn render_python_pin_types_module(contract: &Value) -> Result<String> {
    let component_schemas = component_schemas_of(contract)?;
    let rows = built_in_pin_type_rows(contract)?;
    let mut module = PythonPinTypesModule {
        component_schemas,
        exported_names: BTreeSet::new(),
        nested_classes: BTreeMap::new(),
        definitions: String::new(),
    };

    module.write_literal_alias(
        "PinAnnotationName",
        &property_names_of(component_schemas, PIN_ANNOTATIONS_COMPONENT_NAME)?,
        "An annotation a pin may state: a key of `PinAnnotations`.",
    )?;
    let node_input_mode_schema = component_schemas
        .get(NODE_INPUT_MODE_COMPONENT_NAME)
        .with_context(|| {
            format!("the contract file has no `{NODE_INPUT_MODE_COMPONENT_NAME}` component")
        })?;
    module.write_literal_alias(
        NODE_INPUT_MODE_COMPONENT_NAME,
        &tags_of_a_tagged_union(node_input_mode_schema, NODE_INPUT_MODE_TAG_KEY)
            .with_context(|| format!("`{NODE_INPUT_MODE_COMPONENT_NAME}`"))?,
        &description_of(node_input_mode_schema),
    )?;
    for name in
        component_names_reached_from(component_schemas, PYTHON_PIN_TYPE_ROOT_COMPONENT_NAMES)?
    {
        module.write_component(name, &component_schemas[name])?;
    }
    let mut value_component_names: Vec<&str> = Vec::new();
    for value_component in rows.iter().filter_map(|row| row.value_component) {
        if !value_component_names.contains(&value_component) {
            value_component_names.push(value_component);
        }
    }
    module.write_literal_alias(
        "PinValueComponentName",
        &value_component_names,
        "A contract component that states a built-in pin type's stored value.",
    )?;
    module.write_literal_alias(
        "PinTypeStability",
        PIN_TYPE_STABILITIES,
        "Whether a built-in pin type may still change before it turns stable.",
    )?;
    module.write_built_in_pin_types(&rows)?;

    let mut exported_names: Vec<&String> = module.exported_names.iter().collect();
    exported_names.sort_by_key(|name| (name_sort_group(name), name.as_str()));
    let mut text = String::from(GENERATED_MODULE_HEADER);
    text.push_str("\n__all__ = [\n");
    for name in exported_names {
        writeln!(text, "    \"{name}\",")?;
    }
    text.push_str("]\n");
    text.push_str(&module.definitions);
    Ok(text)
}

struct PythonPinTypesModule<'contract> {
    component_schemas: &'contract Map<String, Value>,
    exported_names: BTreeSet<String>,
    /// Each class written for an object nested in a property, by name, with its schema.
    nested_classes: BTreeMap<String, Value>,
    definitions: String,
}

impl PythonPinTypesModule<'_> {
    fn export(&mut self, name: &str) -> Result<()> {
        ensure!(
            self.exported_names.insert(name.to_owned()),
            "the module would define `{name}` twice"
        );
        Ok(())
    }

    fn write_literal_alias(&mut self, name: &str, values: &[&str], doc: &str) -> Result<()> {
        self.export(name)?;
        let literals = values
            .iter()
            .map(|value| python_string_literal(value, name))
            .collect::<Result<Vec<_>>>()?;
        let one_line = format!("type {name} = Literal[{}]", literals.join(", "));
        if one_line.len() <= PYTHON_LINE_WIDTH {
            write!(self.definitions, "\n\n{one_line}\n")?;
        } else {
            write!(
                self.definitions,
                "\n\ntype {name} = Literal[\n    {},\n]\n",
                literals.join(",\n    ")
            )?;
        }
        self.write_alias_docstring(doc, name)
    }

    fn write_alias_docstring(&mut self, doc: &str, label: &str) -> Result<()> {
        if !doc.trim().is_empty() {
            let docstring = render_docstring(&[python_prose(doc, label)?], 0);
            self.definitions.push_str(&docstring);
        }
        Ok(())
    }

    fn write_component(&mut self, name: &str, schema: &Value) -> Result<()> {
        let python_name = python_name_of_a_component(name);
        let doc = description_of(schema);
        if let Some(alternatives) = schema["oneOf"].as_array() {
            let string_values: Option<Vec<&str>> = alternatives
                .iter()
                .map(|alternative| alternative["const"].as_str())
                .collect();
            if let Some(string_values) = string_values {
                return self.write_literal_alias(&python_name, &string_values, &doc);
            }
            let mut variant_names = Vec::new();
            for alternative in alternatives {
                let variant_name = format!(
                    "{}{python_name}",
                    pascal_case(variant_word_of(alternative).with_context(|| {
                        format!("`{name}` has an alternative that is neither tagged nor one key")
                    })?)
                );
                self.write_typed_dict(
                    &variant_name,
                    alternative,
                    &format!("One form of `{python_name}`."),
                )?;
                variant_names.push(variant_name);
            }
            self.export(&python_name)?;
            let union = variant_names.join(" | ");
            let one_line = format!("type {python_name} = {union}");
            if one_line.len() <= PYTHON_LINE_WIDTH {
                write!(self.definitions, "\n\n{one_line}\n")?;
            } else if union.len() + 4 <= PYTHON_LINE_WIDTH {
                write!(
                    self.definitions,
                    "\n\ntype {python_name} = (\n    {union}\n)\n"
                )?;
            } else {
                write!(
                    self.definitions,
                    "\n\ntype {python_name} = (\n    {}\n)\n",
                    variant_names.join("\n    | ")
                )?;
            }
            return self.write_alias_docstring(&doc, name);
        }
        if schema.get("properties").is_some() {
            return self.write_typed_dict(&python_name, schema, "");
        }
        let python_type = self.python_type_of(schema, &python_name, "")?;
        self.export(&python_name)?;
        write!(self.definitions, "\n\ntype {python_name} = {python_type}\n")?;
        self.write_alias_docstring(&doc, name)
    }

    /// The object `schema` as a `TypedDict` class `class_name`; an object nested in a property
    /// becomes a class of its own, written first.
    fn write_typed_dict(
        &mut self,
        class_name: &str,
        schema: &Value,
        doc_when_it_has_none: &str,
    ) -> Result<()> {
        let required: Vec<&str> = schema["required"]
            .as_array()
            .map(|required| required.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let mut fields = String::new();
        for (key, property_schema) in schema["properties"]
            .as_object()
            .with_context(|| format!("`{class_name}` is not an object with properties"))?
        {
            let label = format!("`{class_name}`'s key `{key}`");
            ensure!(
                is_a_python_field_name(key),
                "{label} is not a name a `TypedDict` class can declare"
            );
            let python_type = self.python_type_of(
                property_schema,
                &pascal_case(key),
                &format!("What a `{key}` key holds."),
            )?;
            if required.contains(&key.as_str()) {
                write!(fields, "\n    {key}: {python_type}\n")?;
            } else {
                write!(fields, "\n    {key}: NotRequired[{python_type}]\n")?;
            }
            let doc = description_of(property_schema);
            if !doc.trim().is_empty() {
                fields.push_str(&render_docstring(&[python_prose(&doc, &label)?], 4));
            }
        }
        self.export(class_name)?;
        write!(self.definitions, "\n\nclass {class_name}(TypedDict):\n")?;
        let mut doc = description_of(schema);
        if doc.trim().is_empty() {
            doc_when_it_has_none.clone_into(&mut doc);
        }
        ensure!(
            !doc.trim().is_empty(),
            "`{class_name}` has no description to write as its docstring"
        );
        let docstring = render_docstring(&[python_prose(&doc, class_name)?], 4);
        self.definitions.push_str(&docstring);
        self.definitions.push_str(&fields);
        Ok(())
    }

    /// `schema` as a Python type. An object with properties becomes the class
    /// `nested_class_name`, documented by `nested_class_doc` when it states no description, and
    /// written once however many keys hold that same object.
    fn python_type_of(
        &mut self,
        schema: &Value,
        nested_class_name: &str,
        nested_class_doc: &str,
    ) -> Result<String> {
        if let Some(name) = component_name_of_a_reference(schema) {
            ensure!(
                self.component_schemas.contains_key(name),
                "`{name}` is referred to but is not a component"
            );
            return Ok(python_name_of_a_component(name));
        }
        if let Some(constant) = schema.get("const") {
            let constant = constant
                .as_str()
                .with_context(|| format!("`{nested_class_name}` is a constant that is not text"))?;
            return Ok(format!(
                "Literal[{}]",
                python_string_literal(constant, nested_class_name)?
            ));
        }
        if let Some(members) = the_union_a_schema_is(schema) {
            let mut alternatives = Vec::new();
            for member in members {
                push_unique(
                    &mut alternatives,
                    self.python_type_of(member, nested_class_name, nested_class_doc)?,
                );
            }
            return Ok(union_of(alternatives));
        }
        if schema.get("properties").is_some() {
            match self.nested_classes.get(nested_class_name) {
                Some(written) if written == schema => {}
                Some(_) => bail!(
                    "two different objects nested under a key would both be the class \
                     `{nested_class_name}`"
                ),
                None => {
                    self.nested_classes
                        .insert(nested_class_name.to_owned(), schema.clone());
                    self.write_typed_dict(nested_class_name, schema, nested_class_doc)?;
                }
            }
            return Ok(nested_class_name.to_owned());
        }
        let json_types: Vec<&str> = match &schema["type"] {
            Value::String(json_type) => vec![json_type.as_str()],
            Value::Array(json_types) => json_types.iter().filter_map(Value::as_str).collect(),
            _ => return Ok("object".to_owned()),
        };
        let mut alternatives = Vec::new();
        for json_type in json_types {
            let python_type = match json_type {
                "string" => "str".to_owned(),
                "integer" => "int".to_owned(),
                "number" => "float".to_owned(),
                "boolean" => "bool".to_owned(),
                "null" => "None".to_owned(),
                "object" => "dict[str, object]".to_owned(),
                "array" => format!(
                    "list[{}]",
                    match schema.get("items") {
                        Some(items) =>
                            self.python_type_of(items, nested_class_name, nested_class_doc)?,
                        None => "object".to_owned(),
                    }
                ),
                other => bail!(
                    "`{nested_class_name}` has the JSON type `{other}`, which this generator does not render"
                ),
            };
            push_unique(&mut alternatives, python_type);
        }
        Ok(union_of(alternatives))
    }

    fn write_built_in_pin_types(&mut self, rows: &[BuiltInPinTypeRow<'_>]) -> Result<()> {
        self.export("PinTypeDescription")?;
        self.export("BUILT_IN_PIN_TYPES")?;
        self.definitions.push_str(
            "\n\n@dataclass(frozen=True, slots=True)\n\
             class PinTypeDescription:\n\
             \x20   \"\"\"One built-in pin type, as the contract lists it.\"\"\"\n\n\
             \x20   name: BuiltInPinTypeName\n\
             \x20   \"\"\"Its name, its `type` tag in a `PinType`.\"\"\"\n\n\
             \x20   label: str\n\
             \x20   \"\"\"What a person reads it as, such as `Encoded video`.\"\"\"\n\n\
             \x20   documentation: str\n\
             \x20   \"\"\"What it carries.\"\"\"\n\n\
             \x20   flows: tuple[PinFlow, ...]\n\
             \x20   \"\"\"How a pin of it may read its messages.\"\"\"\n\n\
             \x20   annotations: tuple[PinAnnotationName, ...]\n\
             \x20   \"\"\"What a pin of it may state besides its type.\"\"\"\n\n\
             \x20   python_forms: tuple[str, ...]\n\
             \x20   \"\"\"Each spelling a Python declaration writes it with.\"\"\"\n\n\
             \x20   value_component: PinValueComponentName | None\n\
             \x20   \"\"\"The component that states its stored value; `None`, it stores none.\"\"\"\n\n\
             \x20   since: int\n\
             \x20   \"\"\"The contract version it was added in.\"\"\"\n\n\
             \x20   stability: PinTypeStability\n\
             \x20   \"\"\"Whether it may still change before it turns stable.\"\"\"\n\n\n\
             BUILT_IN_PIN_TYPES: tuple[PinTypeDescription, ...] = (\n",
        );
        for row in rows {
            let label = format!("the `{}` row", row.name);
            let text = |value: &str| python_string_literal(value, &label);
            let texts = |items: &[&str]| -> Result<Vec<String>> {
                items.iter().map(|item| text(item)).collect()
            };
            self.definitions.push_str("    PinTypeDescription(\n");
            write_text_argument(&mut self.definitions, "name", row.name, &label)?;
            write_text_argument(&mut self.definitions, "label", row.label, &label)?;
            write_text_argument(
                &mut self.definitions,
                "documentation",
                row.documentation,
                &label,
            )?;
            write_tuple_argument(&mut self.definitions, "flows", &texts(&row.flows)?);
            write_tuple_argument(
                &mut self.definitions,
                "annotations",
                &texts(&row.annotations)?,
            );
            write_tuple_argument(
                &mut self.definitions,
                "python_forms",
                &texts(&row.python_forms)?,
            );
            let value_component = match row.value_component {
                Some(value_component) => text(value_component)?,
                None => "None".to_owned(),
            };
            writeln!(
                self.definitions,
                "        value_component={value_component},"
            )?;
            writeln!(
                self.definitions,
                "        since={},",
                row.since_contract_version
            )?;
            write_text_argument(&mut self.definitions, "stability", row.stability, &label)?;
            self.definitions.push_str("    ),\n");
        }
        self.definitions.push_str(")\n");
        Ok(())
    }
}

/// A keyword argument of one `PinTypeDescription(...)` that holds text, split into adjacent
/// literals on word boundaries when one line would pass [`PYTHON_LINE_WIDTH`].
fn write_text_argument(written: &mut String, key: &str, value: &str, label: &str) -> Result<()> {
    let one_line = format!("        {key}={},", python_string_literal(value, label)?);
    if one_line.len() <= PYTHON_LINE_WIDTH {
        writeln!(written, "{one_line}")?;
        return Ok(());
    }
    let chunk_width = PYTHON_LINE_WIDTH - "            \"\"".len();
    let mut chunks: Vec<String> = Vec::new();
    let mut chunk = String::new();
    for word in value.split_inclusive(' ') {
        if !chunk.is_empty() && chunk.len() + word.len() > chunk_width {
            chunks.push(std::mem::take(&mut chunk));
        }
        chunk.push_str(word);
    }
    chunks.push(chunk);
    writeln!(written, "        {key}=(")?;
    for chunk in chunks {
        writeln!(
            written,
            "            {}",
            python_string_literal(&chunk, label)?
        )?;
    }
    writeln!(written, "        ),")?;
    Ok(())
}

/// A keyword argument of one `PinTypeDescription(...)` that holds a tuple of `literals`, one
/// per line when one line would pass [`PYTHON_LINE_WIDTH`].
fn write_tuple_argument(written: &mut String, key: &str, literals: &[String]) {
    let one_line = match literals {
        [only] => format!("        {key}=({only},),"),
        _ => format!("        {key}=({}),", literals.join(", ")),
    };
    if one_line.len() <= PYTHON_LINE_WIDTH {
        let _ = writeln!(written, "{one_line}");
        return;
    }
    let _ = writeln!(written, "        {key}=(");
    for literal in literals {
        let _ = writeln!(written, "            {literal},");
    }
    let _ = writeln!(written, "        ),");
}

/// Where a name sorts in `__all__`, as ruff sorts it: constants, then classes, then the rest.
fn name_sort_group(name: &str) -> u8 {
    if name.chars().all(|character| {
        character.is_ascii_uppercase() || character.is_ascii_digit() || character == '_'
    }) {
        0
    } else if name.starts_with(|first: char| first.is_ascii_uppercase()) {
        1
    } else {
        2
    }
}

fn python_name_of_a_component(name: &str) -> String {
    if name == PIN_DECLARATION_COMPONENT_NAME {
        PIN_DECLARATION_PYTHON_NAME.to_owned()
    } else {
        name.to_owned()
    }
}

/// The word an alternative of a union is named by: its `const` tag, or its one key.
fn variant_word_of(alternative: &Value) -> Option<&str> {
    let properties = alternative["properties"].as_object()?;
    if let Some(tag) = properties
        .values()
        .find_map(|property| property["const"].as_str())
    {
        return Some(tag);
    }
    match properties.keys().collect::<Vec<_>>().as_slice() {
        [only_key] => Some(only_key.as_str()),
        _ => None,
    }
}

fn pascal_case(snake_case: &str) -> String {
    snake_case
        .split('_')
        .map(|word| {
            let mut characters = word.chars();
            characters.next().map_or_else(String::new, |first| {
                first.to_ascii_uppercase().to_string() + characters.as_str()
            })
        })
        .collect()
}

fn is_a_python_field_name(name: &str) -> bool {
    const PYTHON_KEYWORDS: &[&str] = &[
        "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class",
        "continue", "def", "del", "elif", "else", "except", "finally", "for", "from", "global",
        "if", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return",
        "try", "while", "with", "yield",
    ];
    name.chars()
        .next()
        .is_some_and(|first| first.is_ascii_alphabetic() || first == '_')
        && name
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || character == '_')
        && !PYTHON_KEYWORDS.contains(&name)
}

fn description_of(schema: &Value) -> String {
    schema["description"]
        .as_str()
        .unwrap_or_default()
        .to_owned()
}

