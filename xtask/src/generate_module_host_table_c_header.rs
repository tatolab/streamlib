//! Renders `tatolab-module-sdk`'s C header from the module host table's Rust
//! mirror, `sdk/tatolab-module-sdk/src/module_host_table_abi.rs`: every public
//! constant, type alias and `#[repr(C)]` struct, in source order, with its doc.
//! The Rust declaration is the only one; `--check`, also a source-walking gate,
//! fails when the checked-in header drifts from it.

use anyhow::{Context, Result, bail};
use quote::ToTokens;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

const MODULE_HOST_TABLE_ABI_SOURCE_PATH: &str =
    "sdk/tatolab-module-sdk/src/module_host_table_abi.rs";
const MODULE_HOST_TABLE_C_HEADER_PATH: &str =
    "sdk/tatolab-module-sdk/include/tatolab_module_host_table.h";
const MODULE_HOST_TABLE_C_HEADER_INCLUDE_GUARD: &str = "TATOLAB_MODULE_HOST_TABLE_H";

const MODULE_HOST_TABLE_C_HEADER_PREAMBLE: &str = "\
/* Copyright (c) 2025 Jonathan Fontanez
 * SPDX-License-Identifier: GPL-3.0-only */

/* Generated by `cargo xtask generate-module-host-table-c-header` from
 * src/module_host_table_abi.rs. Do not edit: CI fails when this file differs
 * from a regeneration. */
";

/// Regenerate the header, or with `check_only` fail when the checked-in one
/// differs from a regeneration.
pub fn run(workspace_root: &Path, check_only: bool) -> Result<()> {
    let rendered_header = render_the_module_host_table_c_header_from_the_tree(workspace_root)?;
    let header_path = workspace_root.join(MODULE_HOST_TABLE_C_HEADER_PATH);
    if check_only {
        let checked_in_header = std::fs::read_to_string(&header_path)
            .with_context(|| format!("reading {}", header_path.display()))?;
        if checked_in_header != rendered_header {
            bail!(
                "{MODULE_HOST_TABLE_C_HEADER_PATH} differs from what \
                 {MODULE_HOST_TABLE_ABI_SOURCE_PATH} renders to. The table changed without the \
                 header being regenerated: run `cargo xtask generate-module-host-table-c-header` \
                 and commit the result."
            );
        }
        tracing::info!("{MODULE_HOST_TABLE_C_HEADER_PATH} matches the module host table");
        return Ok(());
    }
    if let Some(include_directory) = header_path.parent() {
        std::fs::create_dir_all(include_directory)
            .with_context(|| format!("creating {}", include_directory.display()))?;
    }
    std::fs::write(&header_path, rendered_header)
        .with_context(|| format!("writing {}", header_path.display()))?;
    tracing::info!("wrote {MODULE_HOST_TABLE_C_HEADER_PATH}");
    Ok(())
}

/// The source-walking gate: the checked-in header matches a regeneration.
pub fn check(workspace_root: &Path) -> Result<()> {
    run(workspace_root, true)
}

fn render_the_module_host_table_c_header_from_the_tree(workspace_root: &Path) -> Result<String> {
    let abi_source_path = workspace_root.join(MODULE_HOST_TABLE_ABI_SOURCE_PATH);
    let abi_source = std::fs::read_to_string(&abi_source_path)
        .with_context(|| format!("reading {}", abi_source_path.display()))?;
    render_module_host_table_c_header(&abi_source)
}

/// The C header `abi_source` declares.
pub fn render_module_host_table_c_header(abi_source: &str) -> Result<String> {
    let file = syn::parse_file(abi_source).context("the module host table ABI source parses")?;
    let mut type_alias_scalar_names: BTreeMap<String, String> = BTreeMap::new();
    let mut declarations = String::new();
    for item in &file.items {
        match item {
            syn::Item::Const(item) if is_public(&item.vis) => {
                declarations.push_str(&render_doc_comment(&item.attrs, ""));
                let value = render_constant_value(item, &type_alias_scalar_names)?;
                writeln!(declarations, "#define {} {value}\n", item.ident)?;
            }
            syn::Item::Type(item)
                if is_public(&item.vis) && matches!(item.ty.as_ref(), syn::Type::BareFn(_)) =>
            {
                declarations.push_str(&render_doc_comment(&item.attrs, ""));
                let function_pointer_declarator =
                    render_c_declaration(&item.ty, &item.ident.to_string())
                        .with_context(|| format!("type {}", item.ident))?;
                writeln!(declarations, "typedef {function_pointer_declarator};\n")?;
            }
            syn::Item::Type(item) if is_public(&item.vis) => {
                let scalar_name = item.ty.to_token_stream().to_string();
                let c_type = c_scalar_type_name(&scalar_name).with_context(|| {
                    format!("type {}: only a scalar alias renders to C", item.ident)
                })?;
                declarations.push_str(&render_doc_comment(&item.attrs, ""));
                writeln!(declarations, "typedef {c_type} {};\n", item.ident)?;
                type_alias_scalar_names.insert(item.ident.to_string(), scalar_name);
            }
            syn::Item::Struct(item) if is_public(&item.vis) => {
                if !is_repr_c(&item.attrs) {
                    bail!("{}: only a `#[repr(C)]` struct renders to C", item.ident);
                }
                declarations.push_str(&render_doc_comment(&item.attrs, ""));
                writeln!(declarations, "typedef struct {} {{", item.ident)?;
                for field in &item.fields {
                    let field_name = field
                        .ident
                        .as_ref()
                        .with_context(|| format!("{}: a table field is named", item.ident))?;
                    declarations.push_str(&render_doc_comment(&field.attrs, "    "));
                    let declarator = render_c_declaration(&field.ty, &field_name.to_string())
                        .with_context(|| format!("{}.{field_name}", item.ident))?;
                    writeln!(declarations, "    {declarator};")?;
                }
                writeln!(declarations, "}} {};\n", item.ident)?;
            }
            _ => {}
        }
    }
    let mut header = String::from(MODULE_HOST_TABLE_C_HEADER_PREAMBLE);
    header.push('\n');
    header.push_str(&render_doc_comment(&file.attrs, ""));
    writeln!(
        header,
        "#ifndef {MODULE_HOST_TABLE_C_HEADER_INCLUDE_GUARD}\n\
         #define {MODULE_HOST_TABLE_C_HEADER_INCLUDE_GUARD}\n\n\
         #include <stddef.h>\n\
         #include <stdint.h>\n\n\
         #ifdef __cplusplus\n\
         extern \"C\" {{\n\
         #endif\n"
    )?;
    header.push_str(&declarations);
    writeln!(
        header,
        "#ifdef __cplusplus\n\
         }}\n\
         #endif\n\n\
         #endif /* {MODULE_HOST_TABLE_C_HEADER_INCLUDE_GUARD} */"
    )?;
    Ok(header)
}

fn is_public(visibility: &syn::Visibility) -> bool {
    matches!(visibility, syn::Visibility::Public(_))
}

fn is_repr_c(attributes: &[syn::Attribute]) -> bool {
    attributes.iter().any(|attribute| {
        attribute.path().is_ident("repr")
            && attribute.meta.to_token_stream().to_string().contains('C')
    })
}

/// The C spelling of a Rust scalar, or `None` for anything else.
fn c_scalar_type_name(rust_scalar_name: &str) -> Option<&'static str> {
    Some(match rust_scalar_name {
        "u8" => "uint8_t",
        "u16" => "uint16_t",
        "u32" => "uint32_t",
        "u64" => "uint64_t",
        "usize" => "size_t",
        "i8" => "int8_t",
        "i16" => "int16_t",
        "i32" => "int32_t",
        "i64" => "int64_t",
        "isize" => "ptrdiff_t",
        "f32" => "float",
        "f64" => "double",
        "c_void" => "void",
        _ => return None,
    })
}

/// The `#define` body of a constant: a C string for a `&CStr`, a typed integer
/// otherwise.
fn render_constant_value(
    item: &syn::ItemConst,
    type_alias_scalar_names: &BTreeMap<String, String>,
) -> Result<String> {
    let declared_type_name = item.ty.to_token_stream().to_string().replace(' ', "");
    if declared_type_name == "&CStr" {
        return match item.expr.as_ref() {
            syn::Expr::Lit(syn::ExprLit {
                lit: syn::Lit::CStr(text),
                ..
            }) => Ok(format!("{:?}", text.value().to_string_lossy())),
            _ => bail!("{}: a `&CStr` constant is a `c\"…\"` literal", item.ident),
        };
    }
    let scalar_name = type_alias_scalar_names
        .get(&declared_type_name)
        .cloned()
        .unwrap_or_else(|| declared_type_name.clone());
    let integer = render_integer_expression(&item.expr, &scalar_name)
        .with_context(|| format!("{}: an integer literal or a scalar's bound", item.ident))?;
    if type_alias_scalar_names.contains_key(&declared_type_name) {
        return Ok(format!("(({declared_type_name}){integer})"));
    }
    Ok(integer)
}

fn render_integer_expression(expression: &syn::Expr, scalar_name: &str) -> Result<String> {
    let literal_digits = match expression {
        syn::Expr::Lit(syn::ExprLit {
            lit: syn::Lit::Int(literal),
            ..
        }) => literal.base10_digits().to_string(),
        syn::Expr::Unary(syn::ExprUnary {
            op: syn::UnOp::Neg(_),
            expr,
            ..
        }) => match expr.as_ref() {
            syn::Expr::Lit(syn::ExprLit {
                lit: syn::Lit::Int(literal),
                ..
            }) => format!("-{}", literal.base10_digits()),
            _ => bail!("a negated integer literal"),
        },
        syn::Expr::Path(path) => {
            let rendered_path = path.to_token_stream().to_string().replace(' ', "");
            let (bound_scalar_name, bound) = rendered_path
                .split_once("::")
                .context("a scalar's `MIN` or `MAX`")?;
            let c_type = c_scalar_type_name(bound_scalar_name).context("a scalar's bound")?;
            let c_bound_prefix = c_type.trim_end_matches("_t").to_uppercase();
            return match bound {
                "MIN" | "MAX" => Ok(format!("{c_bound_prefix}_{bound}")),
                _ => bail!("`{rendered_path}` is not a scalar's `MIN` or `MAX`"),
            };
        }
        _ => bail!("an integer literal"),
    };
    Ok(match scalar_name {
        "usize" => format!("((size_t){literal_digits})"),
        "isize" => format!("((ptrdiff_t){literal_digits})"),
        _ => {
            let c_type = c_scalar_type_name(scalar_name)
                .with_context(|| format!("`{scalar_name}` is not an integer scalar"))?;
            let c_constant_macro = c_type.trim_end_matches("_t").to_uppercase();
            format!("{c_constant_macro}_C({literal_digits})")
        }
    })
}

/// `ty` declaring `declarator_name`, in C's inside-out declarator syntax.
fn render_c_declaration(ty: &syn::Type, declarator_name: &str) -> Result<String> {
    match ty {
        syn::Type::Path(path) if path.qself.is_none() => {
            let type_name = path.to_token_stream().to_string().replace(' ', "");
            let c_type = match c_scalar_type_name(&type_name) {
                Some(c_scalar_type) => c_scalar_type,
                None if type_name.starts_with("ModuleHostTable") => type_name.as_str(),
                None => bail!("`{type_name}` has no C spelling"),
            };
            Ok(join_type_and_declarator(c_type, declarator_name))
        }
        syn::Type::Ptr(pointer) => {
            if matches!(pointer.elem.as_ref(), syn::Type::Ptr(_)) {
                bail!("a pointer to a pointer has no C rendering here");
            }
            let qualifier = if pointer.const_token.is_some() {
                "const "
            } else {
                ""
            };
            let pointer_declarator = format!("*{declarator_name}");
            let pointee = render_c_declaration(&pointer.elem, &pointer_declarator)?;
            Ok(format!("{qualifier}{pointee}"))
        }
        syn::Type::Array(array) => {
            let length = array.len.to_token_stream().to_string().replace(' ', "");
            render_c_declaration(&array.elem, &format!("{declarator_name}[{length}]"))
        }
        syn::Type::BareFn(function) => {
            let is_extern_c = function
                .abi
                .as_ref()
                .and_then(|abi| abi.name.as_ref())
                .is_some_and(|name| name.value() == "C");
            if !is_extern_c {
                bail!("a verb is `extern \"C\"`");
            }
            let mut parameters = Vec::new();
            for (index, argument) in function.inputs.iter().enumerate() {
                let parameter_name = argument
                    .name
                    .as_ref()
                    .map(|(name, _)| name.to_string())
                    .unwrap_or_else(|| format!("argument_{index}"));
                parameters.push(render_c_declaration(&argument.ty, &parameter_name)?);
            }
            let parameter_list = if parameters.is_empty() {
                "void".to_string()
            } else {
                parameters.join(", ")
            };
            let function_declarator = format!("(*{declarator_name})({parameter_list})");
            match &function.output {
                syn::ReturnType::Default => {
                    Ok(join_type_and_declarator("void", &function_declarator))
                }
                syn::ReturnType::Type(_, return_type) => {
                    render_c_declaration(return_type, &function_declarator)
                }
            }
        }
        _ => bail!(
            "`{}` has no C spelling",
            ty.to_token_stream().to_string().replace(' ', "")
        ),
    }
}

fn join_type_and_declarator(c_type: &str, declarator: &str) -> String {
    format!("{c_type} {declarator}")
}

/// An item's `///` (or a file's `//!`) doc as a C block comment, with each
/// intra-doc link rendered as the name it links.
fn render_doc_comment(attributes: &[syn::Attribute], indentation: &str) -> String {
    let doc_lines: Vec<String> = attributes
        .iter()
        .filter(|attribute| attribute.path().is_ident("doc"))
        .filter_map(|attribute| match &attribute.meta {
            syn::Meta::NameValue(syn::MetaNameValue {
                value:
                    syn::Expr::Lit(syn::ExprLit {
                        lit: syn::Lit::Str(text),
                        ..
                    }),
                ..
            }) => Some(text.value()),
            _ => None,
        })
        .map(|line| {
            let line = line
                .strip_prefix(' ')
                .unwrap_or(&line)
                .trim_end()
                .to_string();
            line.replace("[`", "`")
                .replace("`]", "`")
                .replace("::", ".")
                .replace("*/", "* /")
        })
        .collect();
    if doc_lines.is_empty() {
        return String::new();
    }
    let mut rendered = format!("{indentation}/**\n");
    for line in doc_lines {
        if line.is_empty() {
            let _ = writeln!(rendered, "{indentation} *");
        } else {
            let _ = writeln!(rendered, "{indentation} * {line}");
        }
    }
    let _ = writeln!(rendered, "{indentation} */");
    rendered
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_checked_in_header_matches_the_module_host_table() {
        let workspace_root = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .expect("xtask sits in the workspace root");
        check(workspace_root).unwrap();
    }

    #[test]
    fn a_verb_renders_as_a_c_function_pointer() {
        let header = render_module_host_table_c_header(
            r#"
            #[repr(C)]
            pub struct ModuleHostTable {
                pub node_host: *mut c_void,
                pub stop_requested: unsafe extern "C" fn(node_host: *mut c_void) -> u32,
                pub log: unsafe extern "C" fn(node_host: *mut c_void, target: *const u8),
            }
            "#,
        )
        .unwrap();
        assert!(header.contains("    void *node_host;\n"), "{header}");
        assert!(
            header.contains("    uint32_t (*stop_requested)(void *node_host);\n"),
            "{header}"
        );
        assert!(
            header.contains("    void (*log)(void *node_host, const uint8_t *target);\n"),
            "{header}"
        );
    }

    #[test]
    fn a_function_pointer_alias_renders_as_a_c_typedef() {
        let header = render_module_host_table_c_header(
            r#"
            pub type ModuleHostTableBlockCallback =
                unsafe extern "C" fn(callback_context: *mut c_void, sample_count: u32);
            "#,
        )
        .unwrap();
        assert!(
            header.contains(
                "typedef void (*ModuleHostTableBlockCallback)(void *callback_context, \
                 uint32_t sample_count);"
            ),
            "{header}"
        );
    }

    #[test]
    fn constants_render_typed() {
        let header = render_module_host_table_c_header(
            r#"
            pub const MODULE_HOST_TABLE_ABI_MAJOR: u32 = 1;
            pub type ModuleHostTableStatus = i32;
            pub const MODULE_HOST_TABLE_STATUS_REFUSED: ModuleHostTableStatus = -1;
            pub const MODULE_HOST_TABLE_TIMESTAMP_NOW: i64 = i64::MIN;
            pub const MODULE_HOST_TABLE_ERROR_MESSAGE_CAPACITY_BYTES: usize = 1024;
            pub const MODULE_HOST_TABLE_PYTHON_CAPSULE_NAME: &CStr = c"tatolab.runtime.x";
            "#,
        )
        .unwrap();
        for expected in [
            "#define MODULE_HOST_TABLE_ABI_MAJOR UINT32_C(1)\n",
            "typedef int32_t ModuleHostTableStatus;\n",
            "#define MODULE_HOST_TABLE_STATUS_REFUSED ((ModuleHostTableStatus)INT32_C(-1))\n",
            "#define MODULE_HOST_TABLE_TIMESTAMP_NOW INT64_MIN\n",
            "#define MODULE_HOST_TABLE_ERROR_MESSAGE_CAPACITY_BYTES ((size_t)1024)\n",
            "#define MODULE_HOST_TABLE_PYTHON_CAPSULE_NAME \"tatolab.runtime.x\"\n",
        ] {
            assert!(
                header.contains(expected),
                "missing {expected:?} in\n{header}"
            );
        }
    }

    #[test]
    fn a_type_with_no_c_spelling_is_refused_naming_the_field() {
        let refusal = render_module_host_table_c_header(
            r#"
            #[repr(C)]
            pub struct ModuleHostTable {
                pub device: VulkanDevice,
            }
            "#,
        )
        .unwrap_err();
        assert!(
            format!("{refusal:#}").contains("ModuleHostTable.device"),
            "{refusal:#}"
        );
    }
}
